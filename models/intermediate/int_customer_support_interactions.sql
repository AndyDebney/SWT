        _line,
        _modified,
        _fivetran_synced,
        interaction_id,
        customer_id,
        order_id,
        product_id,
        interaction_at,
        channel,
        interaction_type,
        issue_category,
        sentiment_score,
        sentiment_label,
        csat_score,
